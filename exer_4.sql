-- BT14
SELECT  DP.MaDatPhong, 
		KH.HoTen,
		P.SoPhong, 
		LP.TenLoaiPhong, 
		DP.NgayNhan, 
		DP.NgayTra,
		DP.TrangThai
FROM  DAT_PHONG DP
INNER JOIN  PHONG P ON P.MaPhong = DP. MaPhong
INNER JOIN KHACH_HANG KH ON DP.MaKH = KH.MaKH
INNER JOIN LOAI_PHONG LP ON LP.MaLoaiPhong = P.MaLoaiPhong
WHERE DP.NgayNhan >= '2026-08-20'
ORDER By DP.NgayNhan DESC;

