;

-- BT8 
-- Từ "và" trong bài tập thì sẽ được hiểu với ý nghĩa là tất cả các phòng trống và chưa từng được đặt
SELECT PHONG.MaPhong, PHONG.SoPhong,
	PHONG.TrangThai
FROM DAT_PHONG
RIGHT JOIN PHONG
ON DAT_PHONG.MaPhong = PHONG.MaPhong
WHERE DAT_PHONG.MaDatPhong IS NULL OR PHONG.TrangThai = 'Trong'
ORDER BY PHONG.SoPhong ASC
;

