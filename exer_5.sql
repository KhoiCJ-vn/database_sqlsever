-- BT21: 
SELECT KH.MaKH, KH.HoTen, COUNT(SD.MaSuDung) AS SOLANSD ,SUM(SD.SoLuong) AS SOLUONGSDDV, MAX(SD.NgaySuDung)
FROM KHACH_HANG KH
INNER JOIN DAT_PHONG DP
ON DP.MaKH = KH.MaKH
INNER JOIN SU_DUNG_DV SD
ON SD.MaDatPhong = DP.MaDatPhong
INNER JOIN DICH_VU DV 
ON DV.MaDV = SD.MaDV
WHERE SD.NgaySuDung >= '2026-09-01'
GROUP BY KH.MaKH, KH.HoTen
HAVING COUNT(SD.MaSuDung) >= 2
;

-- BT22: 
SELECT KH.MaKH, KH.HoTen, DV.TenDV, SUM(SD.SoLuong) AS TONGSOLANSD,SUM(SD.SoLuong*DV.DonGia) AS TONGTIENSUDUNG
FROM KHACH_HANG KH
INNER JOIN DAT_PHONG DP
ON DP.MaKH = KH.MaKH
INNER JOIN SU_DUNG_DV SD
ON SD.MaDatPhong = DP.MaDatPhong
INNER JOIN DICH_VU DV 
ON DV.MaDV = SD.MaDV
GROUP BY KH.MaKH, KH.HoTen, DV.DonGia, DV.TenDV
HAVING SUM(SD.SoLuong) >= 3
;

-- BT23:
SELECT LP.MaLoaiPhong, LP.TenLoaiPhong, COUNT(DISTINCT DP.MaDatPhong) AS SOLUONGDATPHONG, COUNT(SD.MaSuDung) AS SOLANSD, SUM(SD.SoLuong) AS TONGSOLUONG
FROM LOAI_PHONG LP
INNER JOIN PHONG P 
ON P.MaLoaiPhong = LP.MaLoaiPhong
INNER JOIN DAT_PHONG DP 
ON P.MaPhong = DP.MaPhong
INNER JOIN SU_DUNG_DV SD 
ON SD.MaDatPhong = DP.MaDatPhong
WHERE DP.NgayNhan >= '2026-08-20'
GROUP BY LP.MaLoaiPhong, LP.TenLoaiPhong
;

