-- BT13: 
SELECT KH.MaKH, KH.HoTen, SUM(SD.SoLuong*DV.DonGia) AS TONGTIENSUDUNG
FROM KHACH_HANG KH
INNER JOIN DAT_PHONG DP
ON DP.MaKH = KH.MaKH
INNER JOIN SU_DUNG_DV SD
ON SD.MaDatPhong = DP.MaDatPhong
INNER JOIN DICH_VU DV 
ON DV.MaDV = SD.MaDV
GROUP BY KH.MaKH, KH.HoTen
ORDER BY KH.MaKH
;

-- BT14: 
SELECT SD.MaDV, DV.TenDV, SUM(SD.SoLuong) AS SOLUONGSD
FROM SU_DUNG_DV SD
INNER JOIN DICH_VU DV
ON DV.MaDV = SD.MaDV
WHERE SD.NgaySuDung BETWEEN '2026-08-01' AND '2026-08-31'
GROUP BY SD.MaDV, DV.TenDV
;

-- BT15: 
