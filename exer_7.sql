CREATE PROCEDURE TINH_HINH_KHAITHAC_PHONG @MALOAIPHONG VARCHAR(10)
AS 
BEGIN 
	SELECT COUNT(DISTINCT P.SoPhong) AS SOPHONG
		, COUNT(DP.MaDatPhong) AS SOPHIEUDATPHONG
	FROM LOAI_PHONG LP 
	INNER JOIN PHONG P 
	ON LP.MaLoaiPhong = P.MaLoaiPhong
	LEFT JOIN DAT_PHONG DP
	ON DP.MaPhong = P.MaPhong
	WHERE LP.MaLoaiPhong = @MALOAIPHONG;

	SELECT P.SoPhong, COUNT(DP.MaDatPhong) AS SOPHIEUDATPHONG
	FROM LOAI_PHONG LP
	INNER JOIN PHONG P 
	ON LP.MaLoaiPhong = P.MaLoaiPhong
	LEFT JOIN DAT_PHONG DP
	ON DP.MaPhong = P.MaPhong
	WHERE LP.MaLoaiPhong = @MALOAIPHONG
	GROUP BY P.SoPhong;
END;
GO

