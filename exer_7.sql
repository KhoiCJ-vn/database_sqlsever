CREATE FUNCTION fn_TONGTIENDV(@MADATPHONG VARCHAR(10))
RETURNS DECIMAL(12, 2)
AS 
BEGIN 
	DECLARE @TONGTIENDV DECIMAL(12, 2); 
	SELECT @TONGTIENDV = SUM(SD.SoLuong * DV.DonGia)
	FROM SU_DUNG_DV SD 
	INNER JOIN DICH_VU DV 
	ON SD.MaDV = DV.MaDV 
	WHERE @MADATPHONG = SD.MaDatPhong;
	RETURN @TONGTIENDV;
END;
GO

-- Danh sách phiếu đặt phòng kèm tổng tiền dịch vụ 
SELECT DISTINCT DP.MaDatPhong, dbo.fn_TONGTIENDV(DP.MaDatPhong) AS TONGTIENDICHVU
FROM DAT_PHONG DP 
INNER JOIN SU_DUNG_DV SD 
ON DP.MaDatPhong = SD.MaDatPhong;
GO

-- Lọc các phiếu có tổng tiền từ 500000 đồng trở lên 
