CREATE PROCEDURE TH_SU_DUNG_DV
AS 
BEGIN 
	SELECT COUNT(MaDV) AS SOLANSD, SUM(SoLuong) AS SOLUONGSD
	FROM SU_DUNG_DV; 
	
	SELECT DV.MaDV, DV.TenDV
		,COUNT(SD.MaDV) AS SOLANSUDUNG
		,SUM(SD.SoLuong) AS TONGSOLUONGSD
	FROM DICH_VU DV 
	INNER JOIN SU_DUNG_DV SD 
	ON SD.MaDV = DV.MaDV
	GROUP BY DV.MaDV, DV.TenDV;
END;
GO

-- BT4: 
CREATE PROCEDURE KHAI_THAC_DV
AS 
BEGIN
	SELECT COUNT(DISTINCT SD.MaDV) AS SOLUONGDICHVU_DATUNGSD, SUM(SD.SoLuong*DV.DonGia) AS TONGSOTIENPHATSINH
	FROM SU_DUNG_DV SD 
	INNER JOIN DICH_VU DV
	ON SD.MaDV = DV.MaDV;
	
	SELECT DV.MaDV, DV.TenDV, 
		SUM(SD.SoLuong) AS TONGSOLUONGSD, SUM(SD.SoLuong * DV.DonGia) AS TONGTIENDICHVU
	FROM DICH_VU DV 
	INNER JOIN SU_DUNG_DV SD 
	ON SD.MaDV = DV.MaDV
	GROUP BY DV.MaDV, DV.TenDV
	HAVING SUM(SD.SoLuong * DV.DonGia) >= 500000;
END;
GO

