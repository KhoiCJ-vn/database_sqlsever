-- Nghiệp vụ này sẽ liên quan đến việc mình sẽ tạo một hàm function với tham số là mã đặt phòng và mình trả về giá trị doanh thu đến từ việc sử dụng phòng của mã đặt phòng đó
-- Lưu ý: tính thành tiền được bằng cách nhân đơn giá với số ngày.
CREATE FUNCTION fn_REVENUE_MDP(@MADATPHONG VARCHAR(10), @SONGAYLUUTRU INT)
RETURNS DECIMAL(12, 2)
AS 
BEGIN 
	DECLARE @REVENUE DECIMAL(12, 2); 
	SELECT @REVENUE = SUM(LP.DonGia * @SONGAYLUUTRU)
	FROM DAT_PHONG DP 
	INNER JOIN PHONG P
	ON DP.MaPhong = P.MaPhong
	INNER JOIN LOAI_PHONG LP 
	ON LP.MaLoaiPhong = P.MaLoaiPhong
	WHERE DP.MaDatPhong = @MADATPHONG;
	RETURN @REVENUE;
END;
GO

