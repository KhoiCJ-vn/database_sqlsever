CREATE PROCEDURE KH_DAT_PHONG
AS 
BEGIN 
	SELECT 'TONG SO KHACH HANG DA TUNG DAT PHONG' AS NOIDUNG, COUNT(DISTINCT MaKH) AS SOLUONG 
	FROM DAT_PHONG ; 

	SELECT KH.MaKH, KH.HoTen, KH.DienThoai
	FROM KHACH_HANG KH 
	WHERE EXISTS (
		SELECT * 
		FROM DAT_PHONG DP 
		WHERE DP.MaKH = KH.MaKH
	);
END;
GO

