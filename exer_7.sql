CREATE PROCEDURE KH_SD_DV_CAO @SOLUONGDV_TOITHIEU INT, @SOTIENDV_TOITHIEU DECIMAL(12,2)
AS 
BEGIN 
	SELECT 'SO LUONG KHACH HANG THOA DK' AS NOIDUNG
		, COUNT(*) AS SOLUONGKH_THOA_DK
	FROM 
	(SELECT DP.MaKH
	FROM DAT_PHONG DP 
	INNER JOIN SU_DUNG_DV SD 
	ON DP.MaDatPhong = SD.MaDatPhong
	INNER JOIN DICH_VU DV
	ON DV.MaDV = SD.MaDV
	GROUP BY DP.MaKH
	HAVING SUM(SD.SoLuong) >= @SOLUONGDV_TOITHIEU AND SUM(DV.DonGia * SD.SoLuong) >= @SOTIENDV_TOITHIEU) AS TESTS;

	SELECT KH.MaKH, KH.HoTen
		, SUM(SD.SoLuong) AS TONGSOLUONGDV
		, SUM(DV.DonGia * SD.SoLuong) AS TONGTIENDV 
	FROM DAT_PHONG DP 
	INNER JOIN KHACH_HANG KH
	ON KH.MaKH = DP.MaKH
	INNER JOIN SU_DUNG_DV SD 
	ON DP.MaDatPhong = SD.MaDatPhong
	INNER JOIN DICH_VU DV
	ON DV.MaDV = SD.MaDV
	GROUP BY KH.MaKH, KH.HoTen
	HAVING SUM(SD.SoLuong) >= @SOLUONGDV_TOITHIEU AND SUM(DV.DonGia * SD.SoLuong) >= @SOTIENDV_TOITHIEU;
END;
GO

