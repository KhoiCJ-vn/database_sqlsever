CREATE FUNCTION fn_SO_NGAY_LUU_TRU_BAOCAO (@MADATPHONG VARCHAR(10))
RETURNS VARCHAR(30)
AS 
BEGIN 
	DECLARE @SO_NGAY_LUU_TRU VARCHAR(30); 
	SELECT @SO_NGAY_LUU_TRU = (
		CASE 
			WHEN DATEDIFF(day, NgayNhan, NgayTra) <= 30 THEN CAST (DATEDIFF(day, NgayNhan, NgayTra) AS VARCHAR(20)) + ' NGAY'
			WHEN DATEDIFF(day, NgayNhan, NgayTra) > 30 THEN CAST ((FLOOR(DATEDIFF(day, NgayNhan, NgayTra) / 30)) AS VARCHAR(20)) + ' THANG ' + CAST ((DATEDIFF(day, NgayNhan, NgayTra) - (FLOOR(DATEDIFF(day, NgayNhan, NgayTra) / 30)) * 30) AS VARCHAR(10)) + ' NGAY'
		END)
	FROM DAT_PHONG
	WHERE MaDatPhong = @MADATPHONG;
	RETURN @SO_NGAY_LUU_TRU;
END;
GO


-- Nếu chỉ muốn định dạng số ngày là kiểu giá trị int thì bên dưới: 
CREATE FUNCTION fn_SO_NGAY_LUU_TRU (@MADATPHONG VARCHAR(10))
RETURNS VARCHAR(30)
AS 
BEGIN 
	DECLARE @SO_NGAY_LUU_TRU VARCHAR(30); 
	SELECT @SO_NGAY_LUU_TRU = DATEDIFF(day, NgayNhan, NgayTra)
	FROM DAT_PHONG
	WHERE MaDatPhong = @MADATPHONG;
	RETURN @SO_NGAY_LUU_TRU;
END;
GO

