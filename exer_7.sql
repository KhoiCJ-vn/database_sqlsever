CREATE PROCEDURE KHAI_THAC_PHONG
AS 
BEGIN 
-- Bài tập này được hiểu là tổng số phòng đã được đặt có nghĩa là các phòng riêng biệt -> distinct
	SELECT 'TONG SO PHONG DA TUNG DAT' AS NOIDUNG, COUNT(DISTINCT MaPhong) AS TONGSOPHONG
	FROM DAT_PHONG;

	SELECT P.MaPhong, P.SoPhong, LP.TenLoaiPhong
	FROM PHONG P
	INNER JOIN LOAI_PHONG LP
	ON LP.MaLoaiPhong = P.MaLoaiPhong
	WHERE EXISTS (
		SELECT * 
		FROM DAT_PHONG DP 
		WHERE DP.MaPhong = P.MaPhong
	);
END;
GO

